############# without map ###################################################################################################
l = [1,2,3,4,5]
newl =[]
for i in l:
  newl.append(i*i*i)
print(newl)

##output#########################################
# [1, 8, 27, 64, 125]



########################## with map ##################################################################################################################
def cube(num):
  return num*num*num

l = [1,2,3,4,5]
newl = list(map(cube,l))                  # map return map object, so we have to convert it into our desired output like list
print(newl)
##output#########################################
# [1, 8, 27, 64, 125]

